"""Optional LiteLLM OpenAI-compatible proxy lifecycle (Settings toggle).

Peon agent traffic stays in-process. This gateway is for external clients
(OpenCode in the Toolsmith lab). Intent lives in ``PeonSettings``; process side starts
or stops the ``peon-litellm`` container on the Compose network.
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

from django.conf import settings

from agent_runtime.docker.engine import DockerClient
from orchestrator.config import configure, get_config
from orchestrator.utils.service import SharedServiceBase

logger = logging.getLogger(__name__)


def _proxy_config_yaml(model: str, *, api_base: str = "") -> str:
    """Single-chat-model proxy config (matches compose litellm entrypoint)."""
    mid = (model or "").strip()
    if not mid:
        raise ValueError("LITELLM_MODEL is required to start the LLM proxy")
    base = (api_base or "").strip()
    # Prefer LITELLM_API_KEY; fall back to OpenRouter for cloud models.
    key_env = (
        "LITELLM_API_KEY"
        if base or mid.startswith(("ollama/", "ollama_chat/"))
        else "OPENROUTER_API_KEY"
    )
    api_base_lines = "      api_base: os.environ/LITELLM_API_BASE\n" if base else ""
    # model_name must be a YAML plain/quoted scalar; OpenRouter ids contain '/'.
    return (
        "# Generated by Peon when LLM proxy is enabled from Settings.\n"
        "# Chat: LITELLM_MODEL (+ optional LITELLM_API_BASE for Ollama/local).\n"
        "model_list:\n"
        "  - model_name: default\n"
        "    litellm_params:\n"
        "      model: os.environ/LITELLM_MODEL\n"
        f"      api_key: os.environ/{key_env}\n"
        f"{api_base_lines}"
        f"  - model_name: {mid!r}\n"
        "    litellm_params:\n"
        "      model: os.environ/LITELLM_MODEL\n"
        f"      api_key: os.environ/{key_env}\n"
        f"{api_base_lines}"
        "\n"
        "general_settings:\n"
        "  master_key: os.environ/LITELLM_MASTER_KEY\n"
    )


class LlmProxy(SharedServiceBase):
    """Start/stop the LiteLLM /v1 gateway used by OpenCode."""

    def container_name(self) -> str:
        return str(getattr(settings, "LLM_PROXY_CONTAINER", None) or "peon-litellm").strip()

    def image(self) -> str:
        return str(
            getattr(settings, "LLM_PROXY_IMAGE", None) or "ghcr.io/berriai/litellm:main-stable"
        ).strip()

    def master_key(self) -> str:
        return str(getattr(settings, "LITELLM_MASTER_KEY", None) or "sk-peon-litellm").strip()

    def proxy_url(self) -> str:
        return (
            str(getattr(settings, "LLM_PROXY_URL", None) or "http://litellm:4000/v1").strip()
            or "http://litellm:4000/v1"
        )

    def host_port(self) -> int:
        raw = getattr(settings, "LLM_PROXY_PORT", 4000)
        try:
            return max(1, int(raw))
        except (TypeError, ValueError):
            return 4000

    def config_path(self) -> Path:
        root = Path(
            getattr(settings, "PLATFORM_WORKSPACE_DIR", None)
            or (Path.cwd() / "workspaces" / "platform")
        )
        path = root.resolve() / "litellm" / "config.yaml"
        path.parent.mkdir(parents=True, exist_ok=True)
        return path

    @staticmethod
    def intent_enabled() -> bool:
        """Operator intent from Peon Settings (falls back to .env default)."""
        try:
            # circular: runtime_settings ↔ llm_proxy
            from peon.projects.runtime_settings import PeonSettings

            return PeonSettings.get_bool("LLM_PROXY_ENABLED", False)
        except Exception:
            return bool(getattr(settings, "LLM_PROXY_ENABLED", False))

    def sync_orchestrator(self, *, enabled: bool | None = None) -> None:
        on = self.intent_enabled() if enabled is None else bool(enabled)
        try:
            cfg = get_config()
            configure(cfg.merge(llm_proxy_enabled=on, llm_proxy_url=self.proxy_url()))
        except Exception as exc:
            logger.warning("failed to sync llm proxy flag to orchestrator: %s", exc)

    def apply(self, enabled: bool) -> dict[str, Any]:
        """Honor Settings toggle: start or stop the gateway container."""
        self.sync_orchestrator(enabled=bool(enabled))
        if enabled:
            return self.ensure()
        return self.stop()

    def status(self) -> dict[str, Any]:
        cli = DockerClient.shared()
        name = self.container_name()
        ok, err = cli.daemon_ok()
        if not ok:
            return {
                "name": name,
                "exists": False,
                "running": False,
                "docker": False,
                "intent": self.intent_enabled(),
                "url": self.proxy_url(),
                "error": (err or "")[:300],
            }
        exists, running = cli.inspect_running(name)
        # Compose profile may have created peon-litellm-1 instead.
        if not exists:
            for alt in cli.ps_ids("name=peon-litellm"):
                exists, running = cli.inspect_running(alt)
                if exists:
                    name = alt
                    break
        return {
            "name": name,
            "exists": exists,
            "running": running,
            "docker": True,
            "intent": self.intent_enabled(),
            "url": self.proxy_url(),
            "error": "",
        }

    def snapshot(self) -> dict[str, Any]:
        """Operator-facing view: intent + live container status + URL."""
        st = self.status()
        intent = bool(st.get("intent"))
        return {
            "enabled": intent,
            "running": bool(st.get("running")),
            "url": self.proxy_url() if intent else None,
            "status": st,
        }

    def ensure(self) -> dict[str, Any]:
        cli = DockerClient.shared()
        cli.require_daemon()
        name = self.container_name()
        exists, running = cli.inspect_running(name)
        if exists and running:
            return {"ok": True, "action": "reused", "proxy": self.status()}
        if exists and not running:
            start = cli.start(name)
            if not start.ok:
                return {
                    "ok": False,
                    "action": "start_failed",
                    "error": (start.stderr or start.stdout or "").strip()[:400],
                    "proxy": self.status(),
                }
            return {"ok": True, "action": "started", "proxy": self.status()}

        config = self.config_path()
        litellm_model = str(getattr(settings, "LITELLM_MODEL", None) or "").strip()
        if not litellm_model:
            return {
                "ok": False,
                "action": "start_failed",
                "error": "Set LITELLM_MODEL in .env or Peon Settings before enabling the proxy.",
                "proxy": self.status(),
            }
        api_base = str(getattr(settings, "LITELLM_API_BASE", None) or "").strip()
        # Always refresh so the proxy tracks LITELLM_MODEL / API base.
        config.write_text(_proxy_config_yaml(litellm_model, api_base=api_base), encoding="utf-8")
        host_config = cli.host_bind_path(config)
        network = self._compose_network(cli)
        port = self.host_port()
        # Ollama accepts any non-empty key; cloud providers need the real one.
        litellm_key = str(getattr(settings, "LITELLM_API_KEY", None) or "").strip()
        if not litellm_key and api_base:
            litellm_key = "ollama"
        env = {
            "LITELLM_MODEL": litellm_model,
            "LITELLM_API_BASE": api_base,
            "OPENROUTER_API_KEY": str(getattr(settings, "OPENROUTER_API_KEY", None) or ""),
            "LITELLM_API_KEY": litellm_key,
            "LITELLM_MASTER_KEY": self.master_key(),
        }
        create = cli.run_detached(
            name=name,
            image=self.image(),
            workdir="/app",
            network=network,
            network_aliases=["litellm"],
            env=env,
            ports={"4000/tcp": port},
            volumes=[f"{host_config}:/app/config.yaml:ro"],
            labels={"peon.llm_proxy": "1"},
            restart_policy="unless-stopped",
            command=[
                "--config",
                "/app/config.yaml",
                "--host",
                "0.0.0.0",
                "--port",
                "4000",
            ],
        )
        if not create.ok:
            err = (create.stderr or create.stdout or "").strip()
            # Race / name taken by compose service.
            exists2, running2 = cli.inspect_running(name)
            if exists2:
                if not running2:
                    cli.start(name)
                return {"ok": True, "action": "reused", "proxy": self.status()}
            return {
                "ok": False,
                "action": "create_failed",
                "error": err[:500],
                "proxy": self.status(),
            }
        return {"ok": True, "action": "created", "proxy": self.status()}

    def stop(self) -> dict[str, Any]:
        cli = DockerClient.shared()
        name = self.container_name()
        if not cli.available():
            return {
                "ok": False,
                "removed": False,
                "error": "docker unavailable",
                "proxy": self.status(),
            }
        removed = False
        for ref in [name, *cli.ps_ids("label=peon.llm_proxy=1")]:
            res = cli.rm_force(ref)
            if res.ok:
                removed = True
        return {"ok": True, "removed": removed, "proxy": self.status()}

    def _compose_network(self, cli: DockerClient) -> str:
        """Prefer the network this web/worker container is on."""
        preferred = str(getattr(settings, "LLM_PROXY_NETWORK", None) or "peon_default").strip()
        try:
            cid = cli.self_container_id()
            if cid:
                nets = cli.networks(cid)
                if nets:
                    if preferred in nets:
                        return preferred
                    return next(iter(nets.keys()))
        except Exception as exc:
            logger.info("compose network probe failed: %s", exc)
        return preferred
