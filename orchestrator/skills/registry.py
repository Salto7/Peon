"""Skill catalog: one registry, one provider per style."""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Callable, ClassVar

from orchestrator.config import get_config
from orchestrator.skills.providers.base import (
    CLAUDE_PROVIDER,
    PEON_PROVIDER,
    SkillDocument,
    SkillId,
    SkillProvider,
)
from orchestrator.skills.providers.claude_agent import ClaudeAgentSkillsProvider
from orchestrator.skills.mounts import extra_skill_mount
from orchestrator.skills.providers.peon_native import PeonNativeProvider
from orchestrator.skills.registry_scan import discover_skill_manifests
from orchestrator.utils.paths import safe_join
from orchestrator.utils.service import SharedServiceBase

logger = logging.getLogger(__name__)

__all__ = ["SkillRegistry", "discover_skill_manifests"]


def _xml_text(value: str) -> str:
    return (
        (value or "")
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def available_skills_block(docs: list[SkillDocument]) -> str:
    """Progressive index. Catalog-owned; not generated by a shell prompt tool."""
    lines = ["<available_skills>"]
    for doc in docs:
        lines.append("<skill>")
        lines.append(f"<name>{_xml_text(doc.name)}</name>")
        lines.append(f"<description>{_xml_text(doc.description)}</description>")
        lines.append(f"<location>{_xml_text(doc.id)}</location>")
        lines.append("</skill>")
    lines.append("</available_skills>")
    return "\n".join(lines)


class SkillRegistry(SharedServiceBase):
    """Scan configured providers and cache documents by ``SkillId.key``."""

    _provider_factories: ClassVar[
        list[Callable[["SkillRegistry"], SkillProvider]]
    ] = []

    def __init__(self) -> None:
        self._by_key: dict[str, SkillDocument] | None = None
        self._stamp: str = ""

    @classmethod
    def register_provider(
        cls, factory: Callable[["SkillRegistry"], SkillProvider]
    ) -> None:
        """Add a skill style. Bind and the sandbox stay provider-agnostic."""
        if factory not in cls._provider_factories:
            cls._provider_factories.append(factory)

    def skills_dir(self) -> Path:
        return Path(get_config().skills_dir)

    def imported_dir(self) -> Path:
        return Path(get_config().skills_imported_dir)

    def providers(self) -> list[SkillProvider]:
        config = get_config()
        native_root = self.skills_dir().resolve()
        imported_root = self.imported_dir().resolve()
        found = [
            PeonNativeProvider(native_root),
            ClaudeAgentSkillsProvider(imported_root),
        ]
        for index, root in enumerate(config.skills_extra_dirs):
            resolved = Path(root).resolve()
            if resolved in {native_root, imported_root}:
                continue
            found.append(
                ClaudeAgentSkillsProvider(
                    resolved,
                    container_base=extra_skill_mount(index, resolved),
                )
            )
        for factory in self._provider_factories:
            found.append(factory(self))
        return found

    def provider(self, name: str) -> SkillProvider | None:
        key = (name or "").strip().lower()
        if not key:
            return None
        for item in self.providers():
            if item.name == key:
                return item
        return None

    def invalidate(self) -> None:
        self._by_key = None
        self._stamp = ""
        try:
            from orchestrator.utils.commands import clear_command_caches

            clear_command_caches()
        except Exception:
            pass

    def reload_skills(self) -> None:
        """Alias used by Learn save — force a rescan."""
        self.invalidate()

    def _disk_mtime(self) -> float:
        """Legacy max-mtime helper (RoleRegistry / callers)."""
        latest = 0.0
        for provider in self.providers():
            latest = max(latest, provider.mtime())
        return latest

    def _disk_stamp(self) -> str:
        """Fingerprint across providers (manifest casing + sidecars)."""
        parts: list[str] = []
        for provider in self.providers():
            parts.append(
                f"{provider.name}:{provider.root.resolve()}:{provider.fingerprint()}"
            )
        try:
            from peon.projects.role_store import catalog_mtime

            parts.append(f"roles:{catalog_mtime()}")
        except Exception:
            pass
        return "|".join(parts)

    def _scan(self) -> dict[str, SkillDocument]:
        out: dict[str, SkillDocument] = {}
        for provider in self.providers():
            for doc in provider.discover():
                if doc.skill_id.key in out:
                    logger.error("duplicate skill id %s; keeping first", doc.id)
                    continue
                out[doc.skill_id.key] = doc
        return out

    def get_registry(self) -> dict[str, SkillDocument]:
        stamp = self._disk_stamp()
        if self._by_key is None or stamp != self._stamp:
            self._by_key = self._scan()
            self._stamp = stamp
        return self._by_key

    def get(self, skill_id: str) -> SkillDocument | None:
        parsed = SkillId.parse(skill_id)
        if parsed is None:
            return None
        # Built-in providers are always registered; skip rebuilding providers().
        if parsed.provider not in {PEON_PROVIDER, CLAUDE_PROVIDER} and not any(
            p.name == parsed.provider for p in self.providers()
        ):
            return None
        return self.get_registry().get(parsed.key)

    def list_skills(self) -> list[SkillDocument]:
        return sorted(self.get_registry().values(), key=lambda s: (s.provider, s.id))

    def require(self, skill_id: str) -> SkillDocument:
        skill = self.get(skill_id)
        if skill is None:
            known = ", ".join(s.id for s in self.list_skills()) or "(none)"
            raise KeyError(f"unknown skill {skill_id!r}; known: {known}")
        return skill

    def load_text(self, skill_id: str, relative: str = "") -> str:
        skill = self.require(skill_id)
        if not relative:
            return skill.prompt_block()
        if skill.root is None:
            raise FileNotFoundError(f"skill {skill_id!r} has no root")
        path = safe_join(skill.root, relative)
        if path is None or not path.is_file():
            raise FileNotFoundError(f"skill {skill_id!r} missing {relative}")
        return path.read_text(encoding="utf-8")

    def load_path(self, skill: SkillDocument, relative: str) -> Path:
        """Resolve a resource against the document, not provider name.

        Multiple Claude-compatible roots intentionally share the ``claude``
        provider id, so provider-name lookup is ambiguous for external packs.
        """
        if skill.root is None:
            raise FileNotFoundError(f"skill {skill.id!r} has no root")
        path = safe_join(skill.root, relative)
        if path is None or not path.is_file():
            raise FileNotFoundError(f"skill {skill.id!r} missing {relative}")
        return path

    def usable(self, skill_id: str, *, role_id: str = "") -> SkillDocument | None:
        """Return a skill when its dynamically inferred roles permit binding."""
        doc = self.get(skill_id)
        if doc is None:
            return None
        role = (role_id or "").strip().lower()
        if doc.provider == PEON_PROVIDER:
            if not role:
                return doc
        if not role or role not in doc.role_ids:
            return None
        return doc

    def skills_for_role(self, role_id: str) -> tuple[str, ...]:
        """Skill public ids whose inferred affinity includes ``role_id``.

        Ordered: lead skills first, then higher affinity score, then name.
        """
        rid = (role_id or "").strip().lower()
        if not rid:
            return ()
        ranked: list[tuple[float, float, str]] = []
        for doc in self.list_skills():
            if rid not in (doc.role_ids or ()):
                continue
            score_map = dict(doc.affinity_scores or ())
            score = float(score_map.get(rid, 1.0))
            lead = 0.0 if rid in (doc.lead_roles or ()) else 1.0
            ranked.append((lead, -score, doc.id))
        ranked.sort()
        return tuple(item[2] for item in ranked)

    def lead_skill_for_role(self, role_id: str) -> str:
        """Primary lead skill for a role (first after affinity ranking)."""
        bound = self.skills_for_role(role_id)
        return bound[0] if bound else ""
